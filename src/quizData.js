export function calculateResult(answers) {
  // answers = { 1: value, 2: points, ... }
  
  // Проверяем специфические паттерны
  const q1 = answers[1] || 0;
  const q2 = answers[2] || 0;
  const q3 = answers[3] || 0;
  const q4 = answers[4] || 0;
  const q5 = answers[5] || 0;
  const q6 = answers[6] || 0;
  const q7 = answers[7] || 0;
  const q8 = answers[8] || 0;
  
  // Специфические паттерны (приоритет 1)
  
  // Выгоревший котик
  if (q1 + q2 >= 16) {
    return catTypes.burnout;
  }
  
  // Тревожный котик
  if (q5 + q7 >= 15) {
    return catTypes.anxious;
  }
  
  // Broke-котик
  if (q3 >= 7) {
    return catTypes.broke;
  }
  
  // Прокрастинатор
  if (q4 >= 8) {
    return catTypes.procrastinator;
  }
  
  // Делулу-котик
  if (q8 >= 8) {
    return catTypes.delulu;
  }
  
  // Интроверт (бонусный)
  if (q6 <= 3) {
    return catTypes.introvert;
  }
  
  // Общая сумма (приоритет 2)
  const totalScore = Object.values(answers).reduce((sum, val) => sum + val, 0);
  
  if (totalScore <= 25) {
    return catTypes.chill;
  } else if (totalScore <= 50) {
    return catTypes.sigma;
  } else {
    return catTypes.chaos;
  }
}
